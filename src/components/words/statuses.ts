import type { WordStatus } from '@/types/state';

/**
 * Словник самої драбинки знання: як статуси називаються і в якому вони
 * порядку.
 *
 * Це не компонент, а спільне джерело для трьох місць, де драбинка
 * трапляється: картка слова в тексті, картка в словнику і майбутнє
 * тренування. Вигляд у кожного свій — на темній картці в читанні й на білій у
 * словнику однакові кнопки виглядали б однаково недоречно, — а от підписи й
 * порядок мусять збігатися до літери, інакше «вчу» в одному місці й «учу» в
 * іншому читаються як два різні стани.
 */
export const STATUS_LABELS: Record<WordStatus, string> = {
  unknown: 'не знаю',
  hidden: 'приховане',
  learning: 'вчу',
  known: 'знаю',
};

/**
 * Драбинка знання — тільки ті статуси, які читач ставить кнопкою. `hidden`
 * тут навмисно відсутній: приховування живе окремою дією. Набір задає цей
 * явний упорядкований масив, а не ключі мапи підписів — інакше кожен новий
 * статус у мапі сам домальовував би собі кнопку.
 */
export const LADDER_STATUSES: WordStatus[] = ['unknown', 'learning', 'known'];
