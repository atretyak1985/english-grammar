import type { ReactNode } from 'react';

/**
 * Каркас сторінки теми: зміст ліворуч, текст посередині, контекст праворуч.
 *
 * Зміст стоїть саме тут, біля тексту, а не в глобальному меню — бо він
 * потрібен рівно тоді, коли ви читаєте розділ, і рівно для цієї теми. У
 * глобальному сайдбарі він займав місце на кожному екрані застосунку й
 * водночас не траплявся на очі там, де про нього згадують.
 *
 * Без правої колонки каркас стає двоколонковим, а не лишає порожнє місце:
 * суцільне полотно теми читають підряд, і колонка з контекстом там тільки
 * звужувала б рядок.
 *
 * На вузьких екранах колонки лягають одна під одну: зміст перший, бо з
 * нього починають, контекст останній, бо він супровідний.
 */
export function TopicShell({
  contents,
  children,
  aside,
}: {
  contents: ReactNode;
  children: ReactNode;
  aside?: ReactNode;
}) {
  const columns = aside
    ? 'lg:grid-cols-[280px_minmax(0,1fr)_300px]'
    : 'lg:grid-cols-[280px_minmax(0,1fr)]';

  return (
    <div className={`mx-auto grid w-full max-w-shell gap-7 px-9 py-8 ${columns}`}>
      {contents}
      <div className="min-w-0">{children}</div>
      {aside}
    </div>
  );
}
