const FALLBACK = '/account';

/**
 * Валідація параметра `?next=` для повернення після входу (`/login`). Приймається
 * лише локальний шлях: рівно один провідний `/`, без протоколу й хоста. Це
 * єдиний "чистий" (без Next.js) шматок логіки редіректу — тому винесено в
 * окремий модуль, який можна перевірити тестом без застосунку.
 *
 * Небезпечні випадки, які треба відкинути:
 * - `//host/path` і `/\host` — протокол-відносні посилання: браузер трактує
 *   їх як `<поточна схема>://host/path`, тобто зовнішній редірект, який на
 *   вигляд є локальним шляхом (RFC 3986, §4.2, "network-path reference").
 * - `https://evil.com`, `evil.com` — не починаються з одного `/`.
 * - Усе, що не рядок (`undefined`, `null`, число, масив) — `searchParams`
 *   віддає такі значення на дублікатах ключа чи взагалі без ключа.
 *
 * `%2F%2Fevil.com` і подібні URL-екрановані форми сюди не доходять як
 * загроза: Next.js уже декодує значення `searchParams` до чистого рядка, тому
 * `%2F%2Fevil.com` після декодування або перетворюється на `//evil.com` (і
 * ловиться перевіркою вище), або, якщо рядок був закодований двічі, лишається
 * `%2F...` — рядком, що не починається з `/`, і теж відкидається. Тест нижче
 * фіксує саме цю поведінку без рантайму Next.js, а не сподівання на нього.
 */
export function safeNextPath(raw: unknown): string {
  if (typeof raw !== 'string' || raw.length === 0) return FALLBACK;
  if (!raw.startsWith('/')) return FALLBACK;
  if (raw.startsWith('//') || raw.startsWith('/\\')) return FALLBACK;

  return raw;
}
