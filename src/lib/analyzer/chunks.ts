import type { AnalyzedToken } from './tenses';

/**
 * Розбиття документа на шматки для розбору моделлю (CONCEPT 4.1). Ціла книжка
 * одним запитом не йде — і не через контекст моделі, куди вона влізла б, а
 * через рахунок: платити наперед за триста сторінок, з яких прочитають
 * двадцять, безглуздо. Тому розбирається те, що читають.
 *
 * Межі шматків НЕ збігаються з межами сторінок, і це головне рішення тут.
 * Сторінки у читалці рухомі — їх знаходить замір, і вони змінюються від розміру
 * вікна, повного екрана й кількості колонок. Якби ключем кешу був текст
 * сторінки, кожне розгортання вікна створювало б нові ключі й нові платні
 * виклики. Шматки ж залежать тільки від тексту, тому переживають і зміну
 * розміру, і перезапуск, і наступний візит.
 */

/** До скількох слів набираємо шматок, перш ніж шукати кінець речення. */
export const CHUNK_WORDS = 1500;

/**
 * Скільки слів терпимо, не знайшовши кінця речення. Проміжок у 500 слів між
 * цією межею і `CHUNK_WORDS` — запас на пошук: різати посеред речення можна
 * лише тоді, коли крапки не трапилося дуже довго, бо такий розріз здатен
 * розділити конструкцію навпіл.
 */
export const CHUNK_MAX_WORDS = 2000;

export interface Chunk {
  /** Індекс першого токена; завжди слово, ніколи пробіл. */
  start: number;
  /** Індекс останнього токена, включно; теж завжди слово. */
  end: number;
  /** Скільки слів у шматку — для оцінки витрат і для показу покриття. */
  words: number;
}

/**
 * Кінець речення. Закривні лапки й дужки після знака враховуються: інакше
 * `he left."` не вважався б кінцем, і шматок ріс би до жорсткої межі.
 */
function endsSentence(raw: string): boolean {
  return /[.!?][)\]"'”’»]*$/.test(raw);
}

/**
 * Шматки як пари меж у масиві токенів. Обидві межі — саме СЛОВА, і це не
 * дрібниця: текст шматка збирається злиттям токенів, а `tokenize` від рядка,
 * що починається з пробілу, дає зайвий порожній токен на початку — і вся
 * нумерація збіглася б на одиницю.
 */
export function chunksOf(tokens: AnalyzedToken[]): Chunk[] {
  const chunks: Chunk[] = [];

  let start: number | null = null;
  let last = 0;
  let words = 0;

  for (let i = 0; i < tokens.length; i += 1) {
    const token = tokens[i];
    if (!token?.word) continue;

    if (start === null) start = i;
    last = i;
    words += 1;

    const enough = words >= CHUNK_WORDS && endsSentence(token.raw);
    if (enough || words >= CHUNK_MAX_WORDS) {
      chunks.push({ start, end: i, words });
      start = null;
      words = 0;
    }
  }

  // Хвіст коротший за норму — це нормальний шматок, а не залишок: тексти рідко
  // діляться націло, і половина документів складається з одного такого.
  if (start !== null) chunks.push({ start, end: last, words });

  return chunks;
}

/**
 * Текст шматка. Склеюється з `raw`, тому відтворює джерело побайтово — саме це
 * робить хеш стабільним, а кеш придатним для повторного використання.
 */
export function chunkText(tokens: AnalyzedToken[], chunk: Chunk): string {
  let out = '';
  for (let i = chunk.start; i <= chunk.end; i += 1) out += tokens[i]?.raw ?? '';
  return out;
}

/**
 * Шматки, що перетинаються з проміжком `[from, to)` — тобто з тим, що зараз на
 * сторінці. Сторінка часто зачіпає два сусідні шматки, і розбирати треба обидва:
 * інакше половина видимого тексту лишилася б з локальною розміткою.
 */
export function chunksForRange(chunks: Chunk[], from: number, to: number): Chunk[] {
  // Порожній проміжок буває до першого заміру сторінки. Без цієї перевірки
  // `[0,0)` не давав би нічого, а `[5,5)` — цілий шматок, і поведінка на старті
  // залежала б від того, де читач зупинився минулого разу.
  if (to <= from) return [];

  return chunks.filter((chunk) => chunk.start < to && chunk.end >= from);
}
